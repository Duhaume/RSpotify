//! Turns the settings into the files the Pi needs.

use crate::config::Settings;
use std::fmt::Write as _;
use std::path::Path;

pub const DOCKERFILE_SPOTIFY: &str = include_str!("../docker/Dockerfile.spotify");
pub const ENTRYPOINT_SPOTIFY: &str = include_str!("../docker/entrypoint-spotify.sh");
pub const DOCKERFILE_HOTSPOT: &str = include_str!("../docker/Dockerfile.hotspot");
pub const ENTRYPOINT_HOTSPOT: &str = include_str!("../docker/entrypoint-hotspot.sh");
pub const INSTALL_SH: &str = include_str!("../docker/install.sh");
pub const README_MD: &str = include_str!("../docker/LISEZMOI.md");
pub const DOCKERFILE_REGLAGES: &str = include_str!("../docker/Dockerfile.reglages");
pub const REGLAGES_PY: &str = include_str!("../docker/reglages.py");
pub const BUILD_IMAGES_SH: &str = include_str!("../docker/build-images.sh");

pub struct GenFile {
    pub name: &'static str,
    pub content: String,
    pub executable: bool,
    pub secret: bool,
}

pub fn all(s: &Settings) -> Vec<GenFile> {
    vec![
        GenFile { name: "raspotify.conf", content: raspotify_conf(s), executable: false, secret: true },
        GenFile { name: "hotspot.env", content: hotspot_env(s), executable: false, secret: true },
        GenFile { name: ".env", content: dot_env(s), executable: false, secret: true },
        GenFile { name: "docker-compose.yml", content: compose(s), executable: false, secret: false },
        GenFile { name: "docker-compose.images.yml", content: compose_images(s), executable: false, secret: false },
        GenFile { name: "build-images.sh", content: BUILD_IMAGES_SH.into(), executable: true, secret: false },
        GenFile { name: "install.sh", content: INSTALL_SH.into(), executable: true, secret: false },
        GenFile { name: "Dockerfile.spotify", content: DOCKERFILE_SPOTIFY.into(), executable: false, secret: false },
        GenFile { name: "entrypoint-spotify.sh", content: ENTRYPOINT_SPOTIFY.into(), executable: true, secret: false },
        GenFile { name: "Dockerfile.hotspot", content: DOCKERFILE_HOTSPOT.into(), executable: false, secret: false },
        GenFile { name: "entrypoint-hotspot.sh", content: ENTRYPOINT_HOTSPOT.into(), executable: true, secret: false },
        GenFile { name: "Dockerfile.reglages", content: DOCKERFILE_REGLAGES.into(), executable: false, secret: false },
        GenFile { name: "reglages.py", content: REGLAGES_PY.into(), executable: true, secret: false },
        GenFile { name: "LISEZMOI.md", content: README_MD.into(), executable: false, secret: false },
    ]
}

pub fn write_all(s: &Settings, dir: &Path) -> std::io::Result<Vec<String>> {
    std::fs::create_dir_all(dir)?;
    let mut written = Vec::new();
    for f in all(s) {
        let p = dir.join(f.name);
        std::fs::write(&p, &f.content)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = if f.executable { 0o755 } else if f.secret { 0o600 } else { 0o644 };
            std::fs::set_permissions(&p, std::fs::Permissions::from_mode(mode))?;
        }
        written.push(f.name.to_string());
    }
    Ok(written)
}

/// One line of the librespot config: active when `value` is Some.
fn opt(out: &mut String, help: &str, key: &str, value: Option<String>, default: &str) {
    let _ = writeln!(out, "# {help}");
    match value {
        Some(v) => {
            let _ = writeln!(out, "LIBRESPOT_{key}={v}");
        }
        None => {
            let _ = writeln!(out, "#LIBRESPOT_{key}={default}");
        }
    }
    out.push('\n');
}

fn flag(out: &mut String, help: &str, key: &str, on: bool) {
    let _ = writeln!(out, "# {help}");
    let _ = writeln!(out, "{}LIBRESPOT_{key}=", if on { "" } else { "#" });
    out.push('\n');
}

fn non_empty(v: &str) -> Option<String> {
    let t = v.trim();
    (!t.is_empty()).then(|| t.to_string())
}

fn fmt_num(v: f32) -> String {
    if v.fract() == 0.0 { format!("{v:.1}") } else { format!("{v}") }
}

pub fn raspotify_conf(s: &Settings) -> String {
    let sp = &s.speaker;
    let a = &s.advanced;
    let mut o = String::new();
    o.push_str(
        "# raspotify.conf -- librespot settings, mounted in the container as /etc/raspotify/conf\n\
         # Generated by Raspotify Docker. Each LIBRESPOT_FOO_BAR variable is librespot's --foo-bar option.\n\
         # Flags are on when uncommented (an empty value), off when commented.\n\
         # A commented line falls back to librespot's default.\n\n",
    );
    opt(&mut o, "Device name shown in Spotify. Default: \"raspotify (<hostname>)\".", "NAME",
        non_empty(&sp.name).map(|n| sh_quote(&n)), "\"Librespot\"");
    opt(&mut o, "Displayed device type. Default: speaker.", "DEVICE_TYPE",
        (sp.device_type != "speaker").then(|| sp.device_type.clone()), "speaker");
    opt(&mut o, "Bitrate (kbps): 96, 160, 320. Default: 160.", "BITRATE",
        (sp.bitrate != 160).then(|| sp.bitrate.to_string()), "160");
    opt(&mut o, "Audio device (see `aplay -L`). Default: the backend's default.", "DEVICE",
        non_empty(&sp.device), "");
    opt(&mut o, "Output format: F64, F32, S32, S24, S24_3, S16. Default: S16.", "FORMAT",
        (sp.format != "S16").then(|| sp.format.clone()), "S16");
    opt(&mut o, "Dither: none, gpdf, tpdf, tpdf_hp. Default: tpdf for S16/S24/S24_3, none otherwise.", "DITHER",
        (sp.dither != "auto").then(|| sp.dither.clone()), "");
    opt(&mut o, "Mixer: softvol, alsa. Default: softvol.", "MIXER",
        (sp.mixer != "softvol").then(|| sp.mixer.clone()), "softvol");
    opt(&mut o, "ALSA mixer control, e.g. PCM or Master. Default: PCM.", "ALSA_MIXER_CONTROL",
        (sp.mixer == "alsa" && sp.alsa_mixer_control.trim() != "PCM")
            .then(|| sp.alsa_mixer_control.trim().to_string()), "PCM");
    opt(&mut o, "Initial volume in % (0-100). Default for softvol: 50.", "INITIAL_VOLUME",
        sp.set_initial_volume.then(|| sp.initial_volume.min(100).to_string()), "50");
    opt(&mut o, "Volume control: cubic, fixed, linear, log. Default: log.", "VOLUME_CTRL",
        (sp.volume_ctrl != "log").then(|| sp.volume_ctrl.clone()), "log");
    opt(&mut o, "Volume range (dB). Default for softvol: 60.", "VOLUME_RANGE",
        (sp.volume_range != 60.0).then(|| fmt_num(sp.volume_range)), "60");
    opt(&mut o, "Autoplay similar songs: on, off. Default: follow the client setting.", "AUTOPLAY",
        (sp.autoplay != "client").then(|| sp.autoplay.clone()), "on");
    flag(&mut o, "Disable gapless playback.", "DISABLE_GAPLESS", sp.disable_gapless);
    flag(&mut o, "Play all tracks at about the same volume (raspotify turns this on).",
        "ENABLE_VOLUME_NORMALISATION", sp.normalisation);
    let n = sp.normalisation;
    opt(&mut o, "Normalisation method: basic, dynamic. Default: dynamic.", "NORMALISATION_METHOD",
        (n && sp.norm_method != "dynamic").then(|| sp.norm_method.clone()), "dynamic");
    opt(&mut o, "Normalisation gain type: track, album, auto. Default: auto.", "NORMALISATION_GAIN_TYPE",
        (n && sp.norm_gain_type != "auto").then(|| sp.norm_gain_type.clone()), "auto");
    opt(&mut o, "Pregain (dB), -10.0 to 10.0. Default: 0.0.", "NORMALISATION_PREGAIN",
        (n && sp.norm_pregain != 0.0).then(|| fmt_num(sp.norm_pregain)), "0");
    opt(&mut o, "Limiter threshold (dBFS), 0.0 to -10.0. Default: -2.0.", "NORMALISATION_THRESHOLD",
        (n && sp.norm_threshold != -2.0).then(|| fmt_num(sp.norm_threshold)), "-2.0");
    opt(&mut o, "Limiter attack (ms), 1 to 500. Default: 5.", "NORMALISATION_ATTACK",
        (n && sp.norm_attack != 5).then(|| sp.norm_attack.to_string()), "5");
    opt(&mut o, "Limiter release (ms), 1 to 1000. Default: 100.", "NORMALISATION_RELEASE",
        (n && sp.norm_release != 100).then(|| sp.norm_release.to_string()), "100");
    opt(&mut o, "Limiter knee width (dB), 0.0 to 10.0. Default: 5.0.", "NORMALISATION_KNEE",
        (n && sp.norm_knee != 5.0).then(|| fmt_num(sp.norm_knee)), "5.0");

    flag(&mut o, "Disable caching of audio data (protects the SD card).", "DISABLE_AUDIO_CACHE", a.disable_audio_cache);
    flag(&mut o, "Disable caching of credentials.", "DISABLE_CREDENTIAL_CACHE", a.disable_credential_cache);
    opt(&mut o, "Audio cache size limit (K, M, G suffixes).", "CACHE_SIZE_LIMIT",
        if a.disable_audio_cache { None } else { non_empty(&a.cache_size_limit) }, "");
    flag(&mut o, "Disable zeroconf discovery (then an access token is needed).", "DISABLE_DISCOVERY", a.disable_discovery);
    opt(&mut o, "Spotify access token with the 'streaming' scope.", "ACCESS_TOKEN",
        non_empty(&a.access_token), "");
    opt(&mut o, "Port the zeroconf server advertises, 1-65535.", "ZEROCONF_PORT",
        non_empty(&a.zeroconf_port), "");
    opt(&mut o, "Comma-separated interface IPs zeroconf binds to. Default: all.", "ZEROCONF_INTERFACE",
        non_empty(&a.zeroconf_interface), "");
    opt(&mut o, "Connect to a Spotify AP on this port (80, 443, 4070).", "AP_PORT",
        non_empty(&a.ap_port), "");
    opt(&mut o, "HTTP proxy, http://ip:port.", "PROXY", non_empty(&a.proxy), "");
    opt(&mut o, "Program run on playback events.", "ONEVENT", non_empty(&a.onevent), "");
    flag(&mut o, "Only log warnings and errors.", "QUIET", a.quiet && !a.verbose);
    flag(&mut o, "Verbose logs.", "VERBOSE", a.verbose);

    o.push_str(
        "# Not a librespot option: where librespot downloads tracks while playing.\n\
         # /tmp is on disk; commented out, the container keeps them in RAM (/run/raspotify).\n",
    );
    o.push_str(if a.tmp_in_ram { "#TMPDIR=/tmp\n" } else { "TMPDIR=/tmp\n" });
    o
}

pub fn hotspot_env(s: &Settings) -> String {
    let h = &s.hotspot;
    let yn = |b: bool| if b { "yes" } else { "no" };
    let mut o = String::from(
        "# Wi-Fi access point settings, read by the hotspot container at each start.\n\
         # AP_ENABLED=no keeps the container idle and leaves the Wi-Fi card alone.\n",
    );
    let _ = writeln!(o, "AP_ENABLED={}", yn(h.enabled));
    let _ = writeln!(o, "AP_INTERFACE={}", h.interface.trim());
    let _ = writeln!(o, "AP_SSID={}", sh_quote(&h.ssid));
    let _ = writeln!(o, "AP_PASSWORD={}", if h.password.is_empty() { String::new() } else { sh_quote(&h.password) });
    let _ = writeln!(o, "AP_CHANNEL={}", h.channel);
    let _ = writeln!(o, "AP_COUNTRY={}", h.country.trim().to_uppercase());
    let _ = writeln!(o, "AP_ADDRESS={}", h.address.trim());
    let _ = writeln!(o, "AP_PREFIX=24");
    let _ = writeln!(o, "AP_DHCP_START={}", h.dhcp_start.trim());
    let _ = writeln!(o, "AP_DHCP_END={}", h.dhcp_end.trim());
    let _ = writeln!(o, "AP_SHARE_INTERNET={}", yn(h.share_internet));
    let _ = writeln!(o, "AP_UPLINK={}", h.uplink.trim());
    let _ = writeln!(o, "AP_HIDDEN={}", yn(h.hidden));
    o
}

pub fn dot_env(s: &Settings) -> String {
    let mut o = String::from("# Read by docker compose and install.sh\n");
    let _ = writeln!(o, "RASPOTIFY_DEB_URL={}", non_empty(&s.deploy.deb_url).unwrap_or_else(|| "auto".into()));
    let _ = writeln!(o, "AVAHI_MODE={}", if s.advanced.avahi_host { "host" } else { "container" });
    let _ = writeln!(o, "REGLAGES_PORT={}", s.deploy.web_port);
    let _ = writeln!(o, "# Code asked by the settings page (user name: anything). Empty = no code.");
    let _ = writeln!(o, "REGLAGES_CODE={}", s.deploy.web_code.trim());
    o
}

/// Quotes a value for a shell-sourced settings file.
fn sh_quote(v: &str) -> String {
    format!("'{}'", v.replace('\'', "'\\''"))
}

pub fn compose(s: &Settings) -> String {
    compose_with(s, true)
}

/// The same services, using images already compiled and loaded on the Pi
/// (build-images.sh), so the Pi compiles nothing.
pub fn compose_images(s: &Settings) -> String {
    compose_with(s, false)
}

fn compose_with(s: &Settings, with_build: bool) -> String {
    let dbus = if s.advanced.avahi_host {
        "      - /run/dbus:/run/dbus\n"
    } else {
        ""
    };
    let build = |file: &str, args: bool| -> String {
        if with_build {
            let mut b = format!("    build:\n      context: .\n      dockerfile: {file}\n");
            if args {
                b.push_str("      args:\n        RASPOTIFY_DEB_URL: ${RASPOTIFY_DEB_URL:-auto}\n");
            }
            b
        } else {
            // Loaded with `docker load`: never look for them on the internet.
            "    pull_policy: never\n".to_string()
        }
    };
    let b_spotify = build("Dockerfile.spotify", true);
    let b_hotspot = build("Dockerfile.hotspot", false);
    let b_reglages = build("Dockerfile.reglages", false);
    let header = if with_build {
        "# Raspotify dans Docker, tout sur le Pi : l'enceinte Spotify Connect, le point d'accès\n\
         # Wi-Fi (en option) et la page de réglages (http://<nom-du-pi>.local:8080).\n\
         #\n\
         # Compiler les images sur le Pi :   docker compose build\n\
         # Démarrer :                        docker compose up -d     (ou : sudo ./install.sh)\n\
         # Journal :                         docker compose logs -f\n\
         # Arrêter :                         docker compose down\n"
    } else {
        "# Raspotify dans Docker, version « images déjà compilées » : le Pi ne compile rien.\n\
         # Les images viennent de build-images.sh (compilées sur un ordinateur pour le Pi,\n\
         # puis chargées sur le Pi avec docker load).\n\
         #\n\
         # Démarrer :  docker compose -f docker-compose.images.yml up -d\n"
    };
    format!(
        r#"{header}#
# Dans le même dossier : raspotify.conf (réglages du lecteur), hotspot.env (point d'accès),
# .env (port et code de la page de réglages).
name: raspotify

services:
  # Le lecteur Spotify Connect (librespot, du paquet raspotify).
  spotify:
{b_spotify}    image: raspotify-docker/spotify:latest
    container_name: raspotify
    # Spotify trouve l'enceinte par zeroconf (mDNS) : il faut le réseau du Pi lui-même.
    network_mode: host
    restart: unless-stopped
    devices:
      - /dev/snd:/dev/snd
    group_add:
      - audio
    environment:
      AVAHI_MODE: ${{AVAHI_MODE:-container}}
    tmpfs:
      - /run/raspotify:mode=0700
    volumes:
      - ./raspotify.conf:/etc/raspotify/conf:ro
      - spotify-cache:/var/cache/raspotify
      - spotify-state:/var/lib/raspotify
{dbus}
  # Le point d'accès Wi-Fi : en veille tant que AP_ENABLED=no dans hotspot.env.
  hotspot:
{b_hotspot}    image: raspotify-docker/hotspot:latest
    container_name: raspotify-hotspot
    network_mode: host
    restart: unless-stopped
    # hostapd pilote la carte Wi-Fi et le Pi partage internet : il faut tous les droits réseau.
    privileged: true
    volumes:
      - ./hotspot.env:/etc/raspotify/hotspot.env:ro
      - /run/dbus:/run/dbus

  # La page de réglages, à ouvrir depuis un navigateur : http://<nom-du-pi>.local:8080
  reglages:
{b_reglages}    image: raspotify-docker/reglages:latest
    container_name: raspotify-reglages
    network_mode: host
    restart: unless-stopped
    environment:
      REGLAGES_PORT: ${{REGLAGES_PORT:-8080}}
      REGLAGES_CODE: ${{REGLAGES_CODE:-}}
    volumes:
      - .:/data
      # Pour redémarrer le lecteur et le point d'accès après un changement.
      - /var/run/docker.sock:/var/run/docker.sock

volumes:
  spotify-cache:
  spotify-state:
"#
    )
}
